// Command genmigrations writes migrations_generated.go from the canonical .sql
// files in this package.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genmigrations:", err)
		os.Exit(1)
	}
}

func run() error {
	names, err := filepath.Glob("*.sql")
	if err != nil {
		return err
	}
	if len(names) == 0 {
		return fmt.Errorf("no .sql migrations found")
	}
	sort.Strings(names)

	var body bytes.Buffer
	body.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	body.WriteString("// Regenerate with: go generate ./migrations\n\n")
	body.WriteString("package migrations\n\n")
	body.WriteString("// Files maps migration filenames to their canonical SQL bodies.\n")
	body.WriteString("var Files = map[string]string{\n")
	for _, name := range names {
		contents, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&body, "\t%s: %s,\n", strconv.Quote(name), strconv.Quote(string(contents)))
	}
	body.WriteString("}\n")

	formatted, err := format.Source(body.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile("migrations_generated.go", formatted, 0o644); err != nil {
		return err
	}
	return nil
}
